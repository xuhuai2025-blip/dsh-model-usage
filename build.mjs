import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('./', import.meta.url);
const dist = new URL('dist/', root);
const distPath = fileURLToPath(dist);
const fingerprint = text => createHash('sha256').update(text).digest('hex').slice(0, 12);
async function save(url, body) {
  let current;
  try { current = await readFile(url, 'utf8'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (current !== body) await writeFile(url, body);
}
await mkdir(dist, { recursive: true });
const generated = new Map();
const browser = '// Generated by node build.mjs. Edit panel.js instead.\n' + await readFile(new URL('panel.js', root), 'utf8');
const clientEntry = `client.${fingerprint(browser)}.js`;
await save(new URL(clientEntry, dist), browser);
// Keep content-addressed identities for plugin-only ESM/browser reloads.
for (const filename of ['prices.js', 'core.js', 'index.js']) {
  let body = await readFile(new URL(filename, root), 'utf8');
  for (const [dependency, artifact] of generated) body = body.replaceAll('./' + dependency, './' + artifact);
  const artifact = filename.replace(/\.js$/, '.' + fingerprint(body) + '.js');
  await save(new URL(artifact, dist), body);
  generated.set(filename, artifact);
}
const manifest = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
manifest.exports['.'] = './dist/' + generated.get('index.js');
manifest.exports['./client'] = './dist/' + clientEntry;
await save(new URL('package.json', root), JSON.stringify(manifest, null, 2) + '\n');
await save(new URL('cordis.patch.yml', root), `- insert:\n    - id: local-model-usage\n      name: './dist/${generated.get('index.js')}'\n`);
// Remove only obsolete generated artifacts, after checking the absolute target.
const current = new Set([clientEntry, ...generated.values()]);
for (const entry of await readdir(dist, { withFileTypes: true })) {
  if (!entry.isFile() || !/^(client|prices|core|index)\.[a-f0-9]{12}\.js$/.test(entry.name) || current.has(entry.name)) continue;
  const target = resolve(distPath, entry.name);
  if (dirname(target) !== resolve(distPath)) throw new Error('Invalid generated artifact path');
  await unlink(target);
}
console.log('Built model usage (four current content-addressed artifacts).');
